package com.conceptgraph.lessons.poc01;

import com.conceptgraph.llm.ModelFactory;
import dev.langchain4j.data.message.SystemMessage;
import dev.langchain4j.data.message.UserMessage;
import dev.langchain4j.model.chat.ChatModel;
import dev.langchain4j.model.chat.request.ChatRequest;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * POC 1 architect artifact: compare models on latency, speed and answer quality.
 * GET /poc01/model-comparison?models=qwen2.5:3b,qwen2.5:7b   (takes a few minutes on CPU)
 * Writes docs/artifacts/poc01-model-comparison.md and returns the speed summary.
 */
@Tag(name = "POC 1.5 Architect artifact", description = "Measure, then decide: compare models")
@RestController
@RequestMapping("/poc01")
public class Poc01ModelComparisonController {

    private static final List<String> QUESTIONS = List.of(
            "What is an embedding?",
            "What is the difference between RAG and fine-tuning?",
            "Why do LLM apps split documents into chunks?");

    private static final SystemMessage SYSTEM =
            SystemMessage.from("You are a concise AI tutor. Answer in at most 3 sentences.");

    private final ModelFactory models;

    public Poc01ModelComparisonController(ModelFactory models) {
        this.models = models;
    }

    record Run(String model, String question, LlmAnswer answer) {
    }

    @Operation(summary = "Compare models on latency, tokens/s and answers",
            description = "Takes several minutes on CPU. Writes docs/artifacts/poc01-model-comparison.md.")
    @GetMapping("/model-comparison")
    public Map<String, Object> compare(@RequestParam(defaultValue = "qwen2.5:3b,qwen2.5:7b") List<String> models)
            throws IOException {
        List<Run> runs = new ArrayList<>();
        Map<String, Long> coldStartMs = new LinkedHashMap<>();

        for (String name : models) {
            ChatModel model = this.models.chatModel(name, 0.0);

            // First call loads the model into RAM: measured separately (cold start)
            long start = System.nanoTime();
            model.chat("Say OK.");
            coldStartMs.put(name, (System.nanoTime() - start) / 1_000_000);

            for (String q : QUESTIONS) {
                long t = System.nanoTime();
                var response = model.chat(ChatRequest.builder().messages(SYSTEM, UserMessage.from(q)).build());
                runs.add(new Run(name, q, LlmAnswer.of(name, response, (System.nanoTime() - t) / 1_000_000)));
            }
        }

        Path file = writeReport(models, runs, coldStartMs);
        return Map.of("report", file.toAbsolutePath().toString(),
                "coldStartMs", coldStartMs,
                "summary", summary(models, runs));
    }

    private static List<Map<String, Object>> summary(List<String> models, List<Run> runs) {
        return models.stream().map(name -> {
            List<LlmAnswer> mine = runs.stream().filter(r -> r.model().equals(name)).map(Run::answer).toList();
            Map<String, Object> row = new LinkedHashMap<>();
            row.put("model", name);
            row.put("avgSeconds", round(mine.stream().mapToLong(LlmAnswer::millis).average().orElse(0) / 1000));
            row.put("avgOutputTokens", round(mine.stream().mapToInt(a -> a.outputTokens() == null ? 0 : a.outputTokens())
                    .average().orElse(0)));
            row.put("avgTokensPerSecond", round(mine.stream().mapToDouble(LlmAnswer::tokensPerSecond).average().orElse(0)));
            return row;
        }).toList();
    }

    private static double round(double v) {
        return Math.round(v * 10) / 10.0;
    }

    private static Path writeReport(List<String> models, List<Run> runs, Map<String, Long> coldStartMs)
            throws IOException {
        StringBuilder md = new StringBuilder();
        md.append("# POC 1 artifact: model comparison\n\n");
        md.append("Generated by `GET /poc01/model-comparison` on ").append(LocalDate.now())
                .append(". CPU-only laptop, Ollama, temperature 0.\n\n");

        md.append("## Speed summary\n\n| Model | Avg latency (s) | Avg output tokens | Avg tokens/s |\n|---|---|---|---|\n");
        for (Map<String, Object> row : summary(models, runs)) {
            md.append(String.format("| %s | %s | %s | %s |%n", row.get("model"), row.get("avgSeconds"),
                    row.get("avgOutputTokens"), row.get("avgTokensPerSecond")));
        }

        md.append("\n## Cold start (first call loads the model)\n\n| Model | ms |\n|---|---|\n");
        coldStartMs.forEach((model, ms) -> md.append("| ").append(model).append(" | ").append(ms).append(" |\n"));

        md.append("\n## Answers (score quality 1–5 yourself: correct? clear? on-length?)\n\n");
        for (String q : QUESTIONS) {
            md.append("### ").append(q).append("\n\n| Model | Time (s) | Answer | Quality (1–5) |\n|---|---|---|---|\n");
            for (Run r : runs) {
                if (r.question().equals(q)) {
                    md.append(String.format("| %s | %.1f | %s | |%n", r.model(), r.answer().millis() / 1000.0,
                            r.answer().answer().replace("\n", " ").replace("|", "\\|")));
                }
            }
            md.append('\n');
        }
        md.append("## Decision\n\n_Fill in after scoring: which model for fast iteration, which for quality checks, and why._\n");

        // Works whether the app was started from the repo root or from the tutor module
        Path docs = Files.isDirectory(Path.of("docs")) ? Path.of("docs") : Path.of("..", "docs");
        Path file = docs.resolve("artifacts").resolve("poc01-model-comparison.md");
        Files.createDirectories(file.getParent());
        Files.writeString(file, md.toString());
        return file;
    }
}
